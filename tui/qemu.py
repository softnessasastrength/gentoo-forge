"""Short, unprivileged UEFI smoke test using only an owned temporary disk.

This proves QEMU/KVM startup, not Gentoo boot or installation. No host storage,
network, shared directories, ISO, model output or arbitrary QEMU args accepted.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import signal
import socket
import subprocess
import tempfile
import time


def firmware():
    for directory, code, variables in (
        ('/usr/share/OVMF', 'OVMF_CODE_4M.fd', 'OVMF_VARS_4M.fd'),
        ('/usr/share/OVMF', 'OVMF_CODE.fd', 'OVMF_VARS.fd'),
        ('/usr/share/edk2/ovmf', 'OVMF_CODE.fd', 'OVMF_VARS.fd'),
    ):
        pair = (Path(directory) / code, Path(directory) / variables)
        if all(p.is_file() for p in pair):
            return pair
    raise RuntimeError('OVMF firmware missing; run bash setup-dev.sh')


def command(directory, code, accelerator):
    if accelerator not in ('kvm', 'tcg'):
        raise ValueError('Accelerator must be kvm or tcg')
    # All writable paths are generated by TemporaryDirectory, never user devices.
    directory = Path(directory)
    return [
        'qemu-system-x86_64', '-machine', 'q35', '-accel', accelerator,
        '-cpu', 'host' if accelerator == 'kvm' else 'qemu64',
        '-m', '256', '-smp', '1', '-nodefaults', '-no-reboot',
        '-display', 'none', '-device', 'VGA', '-monitor', 'none', '-serial', 'none',
        '-nic', 'none', '-S',
        '-drive', f'if=pflash,format=raw,readonly=on,file={code}',
        '-drive', f'if=pflash,format=raw,file={directory / "vars.fd"}',
        '-drive', f'if=none,id=fixture,format=qcow2,file={directory / "fixture.qcow2"}',
        '-device', 'virtio-blk-pci,drive=fixture,serial=FORGE-SMOKE-ONLY',
        '-qmp', f'unix:{directory / "qmp.sock"},server=on,wait=off',
    ]


class QMP:
    def __init__(self, connection):
        self.stream = connection.makefile('rwb')
        greeting = self.receive()
        if not isinstance(greeting, dict) or 'QMP' not in greeting:
            raise RuntimeError('Invalid QMP greeting')
        self.execute('qmp_capabilities')

    def receive(self):
        line = self.stream.readline(65537)
        if not line or len(line) > 65536:
            raise RuntimeError('Missing or oversized QMP response')
        value = json.loads(line)
        if not isinstance(value, dict):
            raise RuntimeError('Invalid QMP response')
        return value

    def execute(self, name, arguments=None):
        self.stream.write(json.dumps({'execute': name, 'arguments': arguments or {}}).encode() + b'\n')
        self.stream.flush()
        for _ in range(100):
            value = self.receive()
            if 'error' in value:
                raise RuntimeError('QMP command failed: ' + name)
            if 'return' in value:
                return value['return']
        raise RuntimeError('QMP event limit exceeded')


def smoke(accelerator='kvm', seconds=2):
    if os.geteuid() == 0:
        raise PermissionError('Run the VM smoke test as an ordinary user')
    if not 1 <= seconds <= 10:
        raise ValueError('Smoke-test duration must be 1–10 seconds')
    if not all(shutil.which(tool) for tool in ('qemu-system-x86_64', 'qemu-img')):
        raise RuntimeError('QEMU missing; run bash setup-dev.sh')
    code, variables = firmware()
    # Never rely on TMPDIR: commas are QEMU option separators and shared paths
    # can have unexpected semantics. /tmp provides a private generated directory.
    with tempfile.TemporaryDirectory(prefix='forge-qemu-', dir='/tmp') as name:
        directory = Path(name)
        shutil.copyfile(variables, directory / 'vars.fd')
        subprocess.run(['qemu-img', 'create', '-f', 'qcow2', str(directory / 'fixture.qcow2'), '64M'],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=10)
        with (directory / 'stderr').open('wb') as errors:
            process = subprocess.Popen(command(directory, code, accelerator),
                                       stdout=subprocess.DEVNULL, stderr=errors, start_new_session=True)
            try:
                with socket.socket(socket.AF_UNIX) as connection:
                    connection.settimeout(3)
                    deadline = time.monotonic() + 5
                    while True:
                        try:
                            connection.connect(str(directory / 'qmp.sock'))
                            break
                        except (FileNotFoundError, ConnectionRefusedError):
                            if process.poll() is not None or time.monotonic() >= deadline:
                                raise RuntimeError('QEMU startup failed; KVM may be unavailable. Try --accel tcg.')
                            time.sleep(.05)
                    qmp = QMP(connection)
                    try:
                        kvm = qmp.execute('query-kvm')
                        if accelerator == 'kvm' and not kvm.get('enabled'):
                            raise RuntimeError('KVM was requested but is not active')
                        blocks = qmp.execute('query-block')
                        paths = [b['inserted']['file'] for b in blocks if 'inserted' in b]
                        if len(paths) != 3 or any(not Path(p).is_relative_to(directory) and Path(p) != code for p in paths):
                            raise RuntimeError('Unexpected block attachment; refusing to continue')
                        qmp.execute('cont')
                        time.sleep(seconds)
                        status = qmp.execute('query-status')
                        if status.get('status') != 'running':
                            raise RuntimeError('Guest did not remain running')
                        qmp.execute('quit')
                        process.wait(timeout=5)
                        if process.returncode:
                            raise RuntimeError('QEMU exited unexpectedly')
                        return {'result': 'passed', 'accelerator': accelerator,
                                'kvm_enabled': kvm.get('enabled', False), 'firmware': str(code),
                                'guest_status': status['status'], 'memory_mib': 256,
                                'disk_mib': 64, 'network': 'disabled',
                                'installation': 'not attempted', 'firmware_boot': 'unverified',
                                'scope': 'QEMU runs UEFI firmware; guest boot outcome not inspected',
                                'temporary_files': 'removed on exit'}
                    finally:
                        qmp.stream.close()
            finally:
                try:
                    os.killpg(process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                process.wait(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--accel', choices=('kvm', 'tcg'), default='kvm')
    parser.add_argument('--seconds', type=int, default=2)
    args = parser.parse_args()
    try:
        result = smoke(args.accel, args.seconds)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        parser.exit(1, f'Smoke test failed: {exc}\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
